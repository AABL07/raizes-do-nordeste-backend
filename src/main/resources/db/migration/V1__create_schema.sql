CREATE TABLE unidade (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome VARCHAR(150) NOT NULL,
                         regiao VARCHAR(100) NOT NULL,
                         logradouro VARCHAR(200) NOT NULL,
                         numero VARCHAR(20) NOT NULL,
                         complemento VARCHAR(100),
                         bairro VARCHAR(100) NOT NULL,
                         cidade VARCHAR(100) NOT NULL,
                         estado VARCHAR(2) NOT NULL,
                         cep VARCHAR(9) NOT NULL,
                         ativa BOOLEAN NOT NULL
);

CREATE TABLE produto (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome VARCHAR(150) NOT NULL,
                         descricao TEXT,
                         ativo BOOLEAN NOT NULL
);

CREATE TABLE perfil_acesso (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               nome VARCHAR(50) NOT NULL UNIQUE,
                               descricao TEXT,
                               ativo BOOLEAN NOT NULL
);

CREATE TABLE usuario (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         unidade_id BIGINT,
                         perfil_acesso_id BIGINT NOT NULL,
                         nome VARCHAR(150) NOT NULL,
                         login VARCHAR(100) NOT NULL UNIQUE,
                         senha_hash VARCHAR(255) NOT NULL,
                         ativo BOOLEAN NOT NULL,
                         criado_em TIMESTAMP NOT NULL,
                         atualizado_em TIMESTAMP NOT NULL,
                         CONSTRAINT fk_usuario_unidade
                             FOREIGN KEY (unidade_id) REFERENCES unidade(id),
                         CONSTRAINT fk_usuario_perfil_acesso
                             FOREIGN KEY (perfil_acesso_id) REFERENCES perfil_acesso(id)
);

CREATE TABLE cliente (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         usuario_id BIGINT UNIQUE,
                         nome VARCHAR(150) NOT NULL,
                         email VARCHAR(150),
                         telefone VARCHAR(30),
                         ativo BOOLEAN NOT NULL,
                         criado_em TIMESTAMP NOT NULL,
                         atualizado_em TIMESTAMP NOT NULL,
                         CONSTRAINT fk_cliente_usuario
                             FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);

CREATE TABLE pedido (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        unidade_id BIGINT NOT NULL,
                        cliente_id BIGINT,
                        canal_pedido VARCHAR(30) NOT NULL,
                        status VARCHAR(40) NOT NULL,
                        subtotal NUMERIC(12,2) NOT NULL,
                        valor_desconto NUMERIC(12,2) NOT NULL,
                        valor_final NUMERIC(12,2) NOT NULL,
                        criado_em TIMESTAMP NOT NULL,
                        atualizado_em TIMESTAMP NOT NULL,
                        CONSTRAINT fk_pedido_unidade
                            FOREIGN KEY (unidade_id) REFERENCES unidade(id),
                        CONSTRAINT fk_pedido_cliente
                            FOREIGN KEY (cliente_id) REFERENCES cliente(id)
);

CREATE TABLE variacao_produto (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  produto_id BIGINT NOT NULL,
                                  nome VARCHAR(100) NOT NULL,
                                  descricao TEXT,
                                  ativa BOOLEAN NOT NULL,
                                  CONSTRAINT fk_variacao_produto_produto
                                      FOREIGN KEY (produto_id) REFERENCES produto(id)
);

CREATE TABLE item_cardapio (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               unidade_id BIGINT NOT NULL,
                               produto_id BIGINT NOT NULL,
                               variacao_produto_id BIGINT,
                               preco NUMERIC(12,2) NOT NULL,
                               disponivel BOOLEAN NOT NULL,
                               criado_em TIMESTAMP NOT NULL,
                               atualizado_em TIMESTAMP NOT NULL,
                               CONSTRAINT fk_item_cardapio_unidade
                                   FOREIGN KEY (unidade_id) REFERENCES unidade(id),
                               CONSTRAINT fk_item_cardapio_produto
                                   FOREIGN KEY (produto_id) REFERENCES produto(id),
                               CONSTRAINT fk_item_cardapio_variacao
                                   FOREIGN KEY (variacao_produto_id) REFERENCES variacao_produto(id)
);

CREATE TABLE item_pedido (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             pedido_id BIGINT NOT NULL,
                             item_cardapio_id BIGINT NOT NULL,
                             quantidade INTEGER NOT NULL,
                             preco_unitario NUMERIC(12,2) NOT NULL,
                             subtotal NUMERIC(12,2) NOT NULL,
                             CONSTRAINT fk_item_pedido_pedido
                                 FOREIGN KEY (pedido_id) REFERENCES pedido(id),
                             CONSTRAINT fk_item_pedido_item_cardapio
                                 FOREIGN KEY (item_cardapio_id) REFERENCES item_cardapio(id)
);

CREATE TABLE estoque (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         unidade_id BIGINT NOT NULL,
                         produto_id BIGINT NOT NULL,
                         quantidade_fisica INTEGER NOT NULL,
                         quantidade_reservada INTEGER NOT NULL,
                         atualizado_em TIMESTAMP NOT NULL,
                         CONSTRAINT uq_estoque_unidade_produto
                             UNIQUE (unidade_id, produto_id),
                         CONSTRAINT fk_estoque_unidade
                             FOREIGN KEY (unidade_id) REFERENCES unidade(id),
                         CONSTRAINT fk_estoque_produto
                             FOREIGN KEY (produto_id) REFERENCES produto(id)
);

CREATE TABLE reserva_estoque (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 estoque_id BIGINT NOT NULL,
                                 item_pedido_id BIGINT NOT NULL,
                                 quantidade INTEGER NOT NULL,
                                 status VARCHAR(30) NOT NULL,
                                 criado_em TIMESTAMP NOT NULL,
                                 resolvido_em TIMESTAMP,
                                 CONSTRAINT fk_reserva_estoque_estoque
                                     FOREIGN KEY (estoque_id) REFERENCES estoque(id),
                                 CONSTRAINT fk_reserva_estoque_item_pedido
                                     FOREIGN KEY (item_pedido_id) REFERENCES item_pedido(id)
);

CREATE TABLE movimentacao_estoque (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      estoque_id BIGINT NOT NULL,
                                      item_pedido_id BIGINT,
                                      reserva_estoque_id BIGINT UNIQUE,
                                      tipo VARCHAR(30) NOT NULL,
                                      quantidade INTEGER NOT NULL,
                                      motivo VARCHAR(255) NOT NULL,
                                      criado_em TIMESTAMP NOT NULL,
                                      CONSTRAINT fk_movimentacao_estoque_estoque
                                          FOREIGN KEY (estoque_id) REFERENCES estoque(id),
                                      CONSTRAINT fk_movimentacao_estoque_item_pedido
                                          FOREIGN KEY (item_pedido_id) REFERENCES item_pedido(id),
                                      CONSTRAINT fk_movimentacao_estoque_reserva
                                          FOREIGN KEY (reserva_estoque_id) REFERENCES reserva_estoque(id)
);

CREATE TABLE conta_fidelidade (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  cliente_id BIGINT NOT NULL UNIQUE,
                                  saldo_pontos INTEGER NOT NULL,
                                  pontos_reservados INTEGER NOT NULL,
                                  ativa BOOLEAN NOT NULL,
                                  criado_em TIMESTAMP NOT NULL,
                                  atualizado_em TIMESTAMP NOT NULL,
                                  CONSTRAINT fk_conta_fidelidade_cliente
                                      FOREIGN KEY (cliente_id) REFERENCES cliente(id)
);

CREATE TABLE consentimento (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               cliente_id BIGINT NOT NULL,
                               finalidade VARCHAR(30) NOT NULL,
                               status VARCHAR(30) NOT NULL,
                               versao_termo VARCHAR(50) NOT NULL,
                               concedido_em TIMESTAMP NOT NULL,
                               revogado_em TIMESTAMP,
                               CONSTRAINT fk_consentimento_cliente
                                   FOREIGN KEY (cliente_id) REFERENCES cliente(id)
);

CREATE TABLE movimentacao_pontos (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     conta_fidelidade_id BIGINT NOT NULL,
                                     pedido_id BIGINT NOT NULL,
                                     tipo VARCHAR(30) NOT NULL,
                                     quantidade INTEGER NOT NULL,
                                     descricao VARCHAR(255),
                                     criado_em TIMESTAMP NOT NULL,
                                     CONSTRAINT fk_movimentacao_pontos_conta
                                         FOREIGN KEY (conta_fidelidade_id) REFERENCES conta_fidelidade(id),
                                     CONSTRAINT fk_movimentacao_pontos_pedido
                                         FOREIGN KEY (pedido_id) REFERENCES pedido(id)
);

CREATE TABLE registro_auditoria (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    usuario_id BIGINT,
                                    acao VARCHAR(100) NOT NULL,
                                    recurso_tipo VARCHAR(100) NOT NULL,
                                    recurso_id BIGINT,
                                    origem VARCHAR(30) NOT NULL,
                                    detalhes TEXT,
                                    criado_em TIMESTAMP NOT NULL,
                                    CONSTRAINT fk_registro_auditoria_usuario
                                        FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);

CREATE TABLE promocao (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nome VARCHAR(150) NOT NULL,
                          descricao TEXT,
                          tipo_beneficio VARCHAR(30) NOT NULL,
                          valor_beneficio NUMERIC(12,2) NOT NULL,
                          permite_combinacao BOOLEAN NOT NULL,
                          inicio_em TIMESTAMP NOT NULL,
                          fim_em TIMESTAMP NOT NULL,
                          ativa BOOLEAN NOT NULL
);

CREATE TABLE promocao_aplicada (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   pedido_id BIGINT NOT NULL,
                                   promocao_id BIGINT NOT NULL,
                                   tipo_beneficio VARCHAR(30) NOT NULL,
                                   valor_beneficio NUMERIC(12,2) NOT NULL,
                                   valor_desconto_aplicado NUMERIC(12,2) NOT NULL,
                                   aplicado_em TIMESTAMP NOT NULL,
                                   CONSTRAINT fk_promocao_aplicada_pedido
                                       FOREIGN KEY (pedido_id) REFERENCES pedido(id),
                                   CONSTRAINT fk_promocao_aplicada_promocao
                                       FOREIGN KEY (promocao_id) REFERENCES promocao(id)
);

CREATE TABLE tentativa_pagamento (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     pedido_id BIGINT NOT NULL,
                                     chave_idempotencia VARCHAR(100) NOT NULL,
                                     resultado VARCHAR(30) NOT NULL,
                                     valor_solicitado NUMERIC(12,2) NOT NULL,
                                     mensagem_retorno VARCHAR(255),
                                     criado_em TIMESTAMP NOT NULL,
                                     CONSTRAINT uq_tentativa_pagamento_pedido_chave
                                         UNIQUE (pedido_id, chave_idempotencia),
                                     CONSTRAINT fk_tentativa_pagamento_pedido
                                         FOREIGN KEY (pedido_id) REFERENCES pedido(id)
);

CREATE TABLE sazonalidade_produto (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      item_cardapio_id BIGINT NOT NULL,
                                      inicio_em DATE NOT NULL,
                                      fim_em DATE NOT NULL,
                                      ativa BOOLEAN NOT NULL,
                                      CONSTRAINT fk_sazonalidade_produto_item_cardapio
                                          FOREIGN KEY (item_cardapio_id) REFERENCES item_cardapio(id)
);

ALTER TABLE item_cardapio
    ADD CONSTRAINT uq_item_cardapio_unidade_produto_variacao
        UNIQUE NULLS NOT DISTINCT (unidade_id, produto_id, variacao_produto_id);

CREATE UNIQUE INDEX uq_consentimento_ativo_cliente_finalidade
    ON consentimento (cliente_id, finalidade)
    WHERE status = 'ATIVO';

CREATE UNIQUE INDEX uq_movimentacao_pontos_credito_pedido
    ON movimentacao_pontos (pedido_id)
    WHERE tipo = 'CREDITO';